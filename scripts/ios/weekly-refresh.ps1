<#
.SYNOPSIS
    Weekly refresh helper script for Onyx.mx iOS Companion App on Windows 11.

.DESCRIPTION
    PowerShell 5.1 compatible automation for tracking the 7-day profile expiration
    lifecycle and deploying signed OnyxCompanion IPAs to iOS devices over USB.

    IMPORTANT ARCHITECTURAL & SIGNING NOTICE:
    This script DOES NOT sign the IPA itself. Free Apple IDs generate personal provisioning
    profiles that expire after exactly 7 days. pymobiledevice3 is an installation transport
    utility and cannot sign unsigned binaries without local Apple developer certificates.

    The unsigned IPA generated by GitHub Actions MUST be signed first using Sideloadly
    (or AltServer) on Windows 11.

    Exact Workflow Order Supported by Documentation (docs/_inputs/ln/E5.md & E6.md):
    --------------------------------------------------------------------------------
    Order 1 (Recommended Direct Sideloadly Workflow):
      1. Download the unsigned 'OnyxCompanion-unsigned-ipa' artifact from GitHub Actions.
      2. Connect the iPhone 15 Pro via USB to this Windows 11 workstation.
      3. Open Sideloadly, provide your Free Apple ID, drag the unsigned IPA, and click Start.
         Sideloadly injects a 7-day personal provisioning profile and installs the app.
      4. Run this script to record the installation timestamp and track days remaining:
             .\scripts\ios\weekly-refresh.ps1 -IpaPath "C:\path\to\OnyxCompanion.ipa"

    Order 2 (Sideloadly Export-Signed then Install via Script):
      1. Download unsigned IPA from GitHub Actions.
      2. In Sideloadly, sign with your Free Apple ID and use the "Export IPA" feature to save
         the signed package.
      3. Run this script to install via USB and begin tracking:
             .\scripts\ios\weekly-refresh.ps1 -IpaPath "C:\path\to\OnyxCompanion_signed.ipa"
         The script installs the signed package via 'pymobiledevice3 apps install' and writes
         the install date to %LOCALAPPDATA%\OnyxCompanion\last-install.json.

.PARAMETER IpaPath
    Path to the signed OnyxCompanion IPA file. If omitted, the script inspects connected
    devices and reports remaining profile validity without performing an install.

.PARAMETER ModelPath
    Optional path to the ~485 MB LiteRT-LM EmbeddingGemma 2 model file (.litertlm).
    If supplied, provides instructions and attempts documented transfer to Documents/Models.

.PARAMETER DeviceUdid
    Optional target device UDID when multiple iOS devices are attached.

.EXAMPLE
    .\scripts\ios\weekly-refresh.ps1 -IpaPath "C:\dist\OnyxCompanion.ipa"

.EXAMPLE
    .\scripts\ios\weekly-refresh.ps1 -IpaPath "C:\dist\OnyxCompanion.ipa" -ModelPath "C:\models\embeddinggemma-2-740m.litertlm"

.EXAMPLE
    .\scripts\ios\weekly-refresh.ps1 -WhatIf
#>

[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [Parameter(Mandatory = $false, Position = 0, HelpMessage = "Path to the signed OnyxCompanion IPA")]
    [string]$IpaPath,

    [Parameter(Mandatory = $false, Position = 1, HelpMessage = "Optional path to the .litertlm model file (~485 MB)")]
    [string]$ModelPath,

    [Parameter(Mandatory = $false, Position = 2, HelpMessage = "Optional iOS device UDID")]
    [string]$DeviceUdid
)

Set-StrictMode -Off

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "   Onyx.mx iOS Companion - Weekly Refresh & Operations    " -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan

# ---------------------------------------------------------------------------
# 1. Environment Verification: Python & pymobiledevice3
# ---------------------------------------------------------------------------
Write-Host "`n[1/5] Verifying environment prerequisites..." -ForegroundColor Yellow

$pythonCmd = Get-Command "python" -ErrorAction SilentlyContinue
if (-not $pythonCmd) {
    Write-Warning "Python 3 is not found in PATH."
    Write-Host "Install Python 3 from https://www.python.org/ or run:" -ForegroundColor Yellow
    Write-Host "    winget install Python.Python.3.11`n" -ForegroundColor White
} else {
    Write-Host "  [OK] Python detected: $($pythonCmd.Source)" -ForegroundColor Green
}

$pmdCmd = Get-Command "pymobiledevice3" -ErrorAction SilentlyContinue
if (-not $pmdCmd) {
    Write-Warning "pymobiledevice3 is not found in PATH."
    Write-Host "To install pymobiledevice3, run:" -ForegroundColor Yellow
    Write-Host "    pip install -U pymobiledevice3`n" -ForegroundColor Cyan
    Write-Host "Note: Non-Store iTunes or Apple Devices drivers must be installed for usbmuxd communication." -ForegroundColor Gray
} else {
    Write-Host "  [OK] pymobiledevice3 detected: $($pmdCmd.Source)" -ForegroundColor Green
}

# ---------------------------------------------------------------------------
# 2. List Connected iOS Devices
# ---------------------------------------------------------------------------
Write-Host "`n[2/5] Querying connected iOS devices over USB..." -ForegroundColor Yellow

if ($pmdCmd) {
    try {
        pymobiledevice3 usbmux list
    } catch {
        Write-Warning "Failed to list devices via pymobiledevice3: $_"
    }
} else {
    Write-Host "  Skipping usbmux list query because pymobiledevice3 is missing." -ForegroundColor Gray
}

# ---------------------------------------------------------------------------
# 3. Install Signed IPA via pymobiledevice3
# ---------------------------------------------------------------------------
Write-Host "`n[3/5] IPA Installation Check..." -ForegroundColor Yellow

$localAppData = $env:LOCALAPPDATA
if (-not $localAppData) {
    $localAppData = [System.Environment]::GetFolderPath([System.Environment+SpecialFolder]::LocalApplicationData)
}
$configDir = Join-Path $localAppData "OnyxCompanion"
$configFile = Join-Path $configDir "last-install.json"

if ($IpaPath) {
    if (-not (Test-Path -LiteralPath $IpaPath)) {
        Write-Error "The specified IPA file does not exist: $IpaPath"
        return
    }

    $resolvedIpa = (Resolve-Path -LiteralPath $IpaPath).Path
    Write-Host "Target IPA file: $resolvedIpa" -ForegroundColor Cyan

    if ($PSCmdlet.ShouldProcess($resolvedIpa, "Install signed IPA onto iOS device via pymobiledevice3")) {
        if (-not $pmdCmd) {
            Write-Error "pymobiledevice3 is required to install the IPA. Install it via 'pip install -U pymobiledevice3'."
            return
        }

        Write-Host "Installing application to connected device..." -ForegroundColor Cyan
        $installArgs = @()
        if ($DeviceUdid) {
            $installArgs += @("--udid", $DeviceUdid)
        }
        $installArgs += @("apps", "install", $resolvedIpa)

        Write-Host "  Command: pymobiledevice3 $($installArgs -join ' ')" -ForegroundColor Gray
        & pymobiledevice3 @installArgs

        if ($LASTEXITCODE -eq 0 -or $null -eq $LASTEXITCODE) {
            Write-Host "  [OK] IPA installed successfully." -ForegroundColor Green
        } else {
            Write-Warning "Installation exited with code $LASTEXITCODE. Verify device is unlocked and paired."
        }

        # Record install date in %LOCALAPPDATA%\OnyxCompanion\last-install.json
        if (-not (Test-Path -LiteralPath $configDir)) {
            New-Item -ItemType Directory -Path $configDir -Force | Out-Null
        }

        $now = [DateTime]::UtcNow
        $record = [PSCustomObject]@{
            installDateUtc      = $now.ToString("o")
            installedAtLocal    = [DateTime]::Now.ToString("yyyy-MM-dd HH:mm:ss")
            ipaPath             = $resolvedIpa
            deviceUdid          = $(if ($DeviceUdid) { $DeviceUdid } else { "default" })
            profileLifetimeDays = 7
        }
        $recordJson = $record | ConvertTo-Json -Depth 4
        Set-Content -LiteralPath $configFile -Value $recordJson -Encoding UTF8
        Write-Host "  [OK] Recorded install timestamp in $configFile" -ForegroundColor Green
    }
} else {
    Write-Host "  No -IpaPath provided. Skipping IPA install." -ForegroundColor Gray
    Write-Host "  To install or refresh, pass: -IpaPath <path-to-signed-ipa>" -ForegroundColor Gray
}

# ---------------------------------------------------------------------------
# 4. Model Weight Transfer Setup (~485 MB LiteRT-LM)
# ---------------------------------------------------------------------------
Write-Host "`n[4/5] Model Weight Deployment Check (~485 MB .litertlm)..." -ForegroundColor Yellow

if ($ModelPath) {
    if (-not (Test-Path -LiteralPath $ModelPath)) {
        Write-Warning "Specified model file not found: $ModelPath"
    } else {
        $resolvedModel = (Resolve-Path -LiteralPath $ModelPath).Path
        $modelName = [System.IO.Path]::GetFileName($resolvedModel)
        Write-Host "Model file: $resolvedModel" -ForegroundColor Cyan
        Write-Host "Runtime lookup order: (1) Documents/Models/*.litertlm, (2) App bundle, (3) Remote download" -ForegroundColor Gray

        Write-Host "`n[UNVERIFIED] Direct CLI file copy via pymobiledevice3 on iOS 17 non-jailbroken devices:" -ForegroundColor Yellow
        Write-Host "  The exact pymobiledevice3 subcommand for direct pushing into app container Documents" -ForegroundColor Gray
        Write-Host "  (e.g., 'pymobiledevice3 afc put' or 'pymobiledevice3 house-arrest') is UNVERIFIED on iOS 17+." -ForegroundColor Gray
        Write-Host "  If CLI transfer fails, use the official Apple Devices GUI method below." -ForegroundColor Gray

        Write-Host "`nOfficial Drag-and-Drop Method (Apple Devices App / iTunes on Windows 11):" -ForegroundColor Green
        Write-Host "  1. Connect your iPhone 15 Pro to Windows 11 via USB."
        Write-Host "  2. Launch 'Apple Devices' (Microsoft Store) or classic iTunes."
        Write-Host "  3. Select your device -> Click 'Files' (or 'File Sharing')."
        Write-Host "  4. Select 'OnyxCompanion' from the apps list."
        Write-Host "  5. Drag '$modelName' into the Documents folder (or into a 'Models' subfolder)."
        Write-Host "  6. Click Sync / Done. Model persists across future weekly re-signs."
    }
} else {
    Write-Host "  No -ModelPath provided. Skipping model weight copy." -ForegroundColor Gray
    Write-Host "  (The ~485 MB model is only copied once and survives weekly app refreshes)." -ForegroundColor Gray
}

# ---------------------------------------------------------------------------
# 5. Profile Expiration Tracking (7-day personal provisioning limit)
# ---------------------------------------------------------------------------
Write-Host "`n[5/5] Checking Profile Lifetime (7-day Free Apple ID Limit)..." -ForegroundColor Yellow

if (Test-Path -LiteralPath $configFile) {
    try {
        $jsonContent = Get-Content -Raw -LiteralPath $configFile | ConvertFrom-Json
        $installUtc = [DateTime]::Parse($jsonContent.installDateUtc)
        $elapsed = [DateTime]::UtcNow - $installUtc
        $totalDays = $elapsed.TotalDays
        $daysRemaining = 7.0 - $totalDays
        $daysRounded = [Math]::Round($daysRemaining, 1)

        Write-Host "  Last Installed: $($jsonContent.installedAtLocal)" -ForegroundColor Cyan
        Write-Host "  Tracked IPA:    $($jsonContent.ipaPath)" -ForegroundColor Gray

        if ($daysRemaining -le 0) {
            Write-Host "`n  ========================================================" -ForegroundColor Red
            Write-Host "  [!] STATUS: PROFILE EXPIRED ($([Math]::Abs($daysRounded)) days ago)!" -ForegroundColor Red
            Write-Host "  The app cannot open on the iPhone ('Unable to Verify App')." -ForegroundColor Red
            Write-Host "  ACTION: Re-sign the IPA with Sideloadly and install now." -ForegroundColor Red
            Write-Host "  ========================================================`n" -ForegroundColor Red
        } elseif ($daysRemaining -le 2.0) {
            Write-Host "`n  ========================================================" -ForegroundColor Yellow
            Write-Host "  [!] STATUS: EXPIRING SOON! Remaining: $daysRounded days." -ForegroundColor Yellow
            Write-Host "  WARNING: Profile expires in less than 48 hours." -ForegroundColor Yellow
            Write-Host "  Re-sign with Sideloadly within 2 days to avoid downtime." -ForegroundColor Yellow
            Write-Host "  ========================================================`n" -ForegroundColor Yellow
        } else {
            Write-Host "  [OK] STATUS: ACTIVE. Remaining: $daysRounded days." -ForegroundColor Green
        }
    } catch {
        Write-Warning "Could not parse installation record at ${configFile}: $_"
    }
} else {
    Write-Host "  No prior install history found at $configFile." -ForegroundColor Gray
    Write-Host "  Run this script with -IpaPath after signing to initialize the 7-day tracker." -ForegroundColor Gray
}

Write-Host "`nWeekly refresh operation complete.`n" -ForegroundColor Cyan
